import 'dart:convert';

enum OtpSource {
  sms,
  email,
  messenger,
  notification,
  manualTest,
}

enum TransportType {
  wifiLan,
  usb,
  bluetooth,
}

enum ParserSensitivity {
  strict,
  balanced,
  relaxed,
}

extension OtpSourceX on OtpSource {
  String get wireValue => name;

  static OtpSource fromWire(String? value) {
    return OtpSource.values.firstWhere(
      (e) => e.name == value,
      orElse: () => OtpSource.notification,
    );
  }
}

extension TransportTypeX on TransportType {
  String get wireValue => name;

  static TransportType fromWire(String? value) {
    return TransportType.values.firstWhere(
      (e) => e.name == value,
      orElse: () => TransportType.wifiLan,
    );
  }
}

/// Represents a detected OTP event transferred from Android to Desktop.
class OtpMessage {
  OtpMessage({
    required this.id,
    required this.code,
    required this.sender,
    required this.source,
    required this.timestampMs,
    this.transport = TransportType.wifiLan,
    this.confidence = 1.0,
    this.packageName,
    this.snippet,
    this.autoCopied = false,
  });

  final String id;
  final String code;
  final String sender;
  final OtpSource source;
  final int timestampMs;
  final TransportType transport;
  final double confidence;
  final String? packageName;

  /// Optional short redacted snippet (only sent if user enables it).
  final String? snippet;
  final bool autoCopied;

  DateTime get receivedAt => DateTime.fromMillisecondsSinceEpoch(timestampMs);

  OtpMessage copyWith({
    TransportType? transport,
    bool? autoCopied,
  }) {
    return OtpMessage(
      id: id,
      code: code,
      sender: sender,
      source: source,
      timestampMs: timestampMs,
      transport: transport ?? this.transport,
      confidence: confidence,
      packageName: packageName,
      snippet: snippet,
      autoCopied: autoCopied ?? this.autoCopied,
    );
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'code': code,
        'sender': sender,
        'source': source.wireValue,
        'ts': timestampMs,
        'transport': transport.wireValue,
        'confidence': confidence,
        if (packageName != null) 'pkg': packageName,
        if (snippet != null) 'snippet': snippet,
      };

  factory OtpMessage.fromJson(Map<String, dynamic> json) {
    return OtpMessage(
      id: (json['id'] as String?) ?? '',
      code: (json['code'] as String?) ?? '',
      sender: (json['sender'] as String?) ?? 'Unknown',
      source: OtpSourceX.fromWire(json['source'] as String?),
      timestampMs: (json['ts'] as num?)?.toInt() ??
          DateTime.now().millisecondsSinceEpoch,
      transport: TransportTypeX.fromWire(json['transport'] as String?),
      confidence: (json['confidence'] as num?)?.toDouble() ?? 1.0,
      packageName: json['pkg'] as String?,
      snippet: json['snippet'] as String?,
    );
  }

  String toJsonString() => jsonEncode(toJson());
}

/// QR / Manual pairing payload generated by Desktop and scanned by Android.
class PairingPayload {
  PairingPayload({
    required this.version,
    required this.deviceId,
    required this.deviceName,
    required this.sharedKeyBase64,
    required this.lanIps,
    required this.tcpPort,
    this.bluetoothAddress,
  });

  final int version;
  final String deviceId;
  final String deviceName;
  final String sharedKeyBase64;
  final List<String> lanIps;
  final int tcpPort;
  final String? bluetoothAddress;

  Map<String, dynamic> toJson() => {
        'v': version,
        'id': deviceId,
        'n': deviceName,
        'k': sharedKeyBase64,
        'ips': lanIps,
        'p': tcpPort,
        if (bluetoothAddress != null && bluetoothAddress!.isNotEmpty)
          'bt': bluetoothAddress,
      };

  /// Encodes as compact URI: `otpbridge://pair?d=<base64url(json)>`
  String toUriString() {
    final jsonBytes = utf8.encode(jsonEncode(toJson()));
    final encoded = base64Url.encode(jsonBytes).replaceAll('=', '');
    return 'otpbridge://pair?d=$encoded';
  }

  static PairingPayload? tryParse(String raw) {
    try {
      final trimmed = raw.trim();
      String jsonText;
      if (trimmed.startsWith('otpbridge://')) {
        final uri = Uri.parse(trimmed);
        final data = uri.queryParameters['d'];
        if (data == null || data.isEmpty) return null;
        final padded = base64Url.normalize(data);
        jsonText = utf8.decode(base64Url.decode(padded));
      } else if (trimmed.startsWith('{')) {
        jsonText = trimmed;
      } else {
        final padded = base64Url.normalize(trimmed);
        jsonText = utf8.decode(base64Url.decode(padded));
      }

      final map = jsonDecode(jsonText) as Map<String, dynamic>;
      final key = map['k'] as String?;
      final id = map['id'] as String?;
      if (key == null || key.isEmpty || id == null || id.isEmpty) return null;

      final keyBytes = base64Url.decode(base64Url.normalize(key));
      if (keyBytes.length != 32) return null;

      return PairingPayload(
        version: (map['v'] as num?)?.toInt() ?? 1,
        deviceId: id,
        deviceName: (map['n'] as String?) ?? 'Desktop',
        sharedKeyBase64: key,
        lanIps: ((map['ips'] as List?) ?? const [])
            .map((e) => e.toString())
            .where((e) => e.isNotEmpty)
            .toList(),
        tcpPort: (map['p'] as num?)?.toInt() ?? 47831,
        bluetoothAddress: map['bt'] as String?,
      );
    } catch (_) {
      return null;
    }
  }
}
